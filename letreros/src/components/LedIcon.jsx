export default function LedIcon({ name, size = 22, color = '#ff4fb0', lit = true, title }) {
  const rows = GRIDS[name] || GRIDS.star
  const dots = []
  rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && dots.push([x, y])))
  return (
    <svg className="led-icon" width={size} height={size} viewBox="-0.5 -0.5 9 9" role={title ? 'img' : undefined} aria-hidden={title ? undefined : true} aria-label={title}>
      {lit && (
        <g opacity="0.45" style={{ filter: 'blur(0.35px)' }}>
          {dots.map(([x, y]) => <circle key={`g${x}-${y}`} cx={x} cy={y} r="0.62" fill={color} />)}
        </g>
      )}
      {dots.map(([x, y]) => <circle key={`${x}-${y}`} cx={x} cy={y} r="0.36" fill={lit ? color : '#c9c4c7'} />)}
      {lit && dots.map(([x, y]) => <circle key={`h${x}-${y}`} cx={x - 0.1} cy={y - 0.12} r="0.13" fill="#fff" opacity="0.85" />)}
    </svg>
  )
}
