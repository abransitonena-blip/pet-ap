  box: ['...###...', '.##...##.', '#.......#', '###...###', '#..###..#', '#...#...#', '#...#...#', '.##.#.##.', '...###...'],
  card: ['.........', '#########', '#.......#', '#########', '#########', '#.......#', '#.##..#.#', '#########', '.........'],
  star: ['....#....', '....#....', '...###...', '#########', '.#######.', '..#####..', '..##.##..', '.##...##.', '.#.....#.'],
  camera: ['.........', '...###...', '#########', '#...#...#', '#..#.#..#', '#.#...#.#', '#..#.#..#', '#...#...#', '#########'],
  image: ['#########', '#.......#', '#.##....#', '#.##....#', '#.....#.#', '#....###.', '#.#.#####', '#########', '#########'],
  printer: ['..#####..', '..#...#..', '#########', '#.......#', '#.....#.#', '#########', '..#...#..', '..#...#..', '..#####..'],
